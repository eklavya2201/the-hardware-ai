#!/usr/bin/env node
/**
 * One-shot local setup for Synqit CAD.
 *
 *   node scripts/bootstrap.mjs --azure-key <AZURE_OPENAI_API_KEY> [--azure-resource aatreus]
 *                              [--google-client-id <id>] [--no-guest] [--force] [--out .env.local]
 *
 * What it does, in order:
 *   1. Checks Node >= 20.19 and that Docker is running.
 *   2. `npx supabase start` (idempotent; first run pulls ~13 images, 2-3 minutes).
 *   3. Reads ANON_KEY / SERVICE_ROLE_KEY from `npx supabase status -o env`.
 *   4. Writes .env.local (refuses to overwrite unless --force).
 *   5. Creates the confirmed guest account for no-auth mode (unless --no-guest).
 *   6. Tells you to run `npm run dev`.
 *
 * Nothing here needs any secret except the Azure OpenAI key you pass in.
 * No dependencies beyond Node itself.
 */
import { execSync, spawnSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';

const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : dflt;
};
const flag = (name) => args.includes(name);

const AZURE_KEY = opt('--azure-key', process.env.AZURE_OPENAI_API_KEY || '');
const AZURE_RESOURCE = opt('--azure-resource', process.env.AZURE_RESOURCE_NAME || 'aatreus');
const GOOGLE_CLIENT_ID = opt('--google-client-id', process.env.GOOGLE_CLIENT_ID || '');
const OUT = opt('--out', '.env.local');
const GUEST_EMAIL = 'guest@synqit.in';
const GUEST_PASSWORD = process.env.GUEST_PASSWORD || `Guest-${randomBytes(6).toString('hex')}!`;

const fail = (msg) => {
  console.error(`\n✖ ${msg}`);
  process.exit(1);
};
const ok = (msg) => console.log(`✔ ${msg}`);

// 1. prerequisites
const [maj, min] = process.versions.node.split('.').map(Number);
if (maj < 20 || (maj === 20 && min < 19)) fail(`Node ${process.versions.node} found; need 20.19+ or 22.12+`);
ok(`Node ${process.versions.node}`);
if (!AZURE_KEY) fail('Missing --azure-key (the Azure OpenAI key; ask the repo owner)');
try {
  execSync('docker info', { stdio: 'ignore' });
  ok('Docker is running');
} catch {
  fail('Docker is not running. Start Docker Desktop, wait for the whale icon, then rerun.');
}
if (existsSync(OUT) && !flag('--force')) fail(`${OUT} already exists; pass --force to overwrite`);

// 2. supabase start (env() references in supabase/config.toml read these)
const sbEnv = { ...process.env, GOOGLE_CLIENT_ID, GOOGLE_SECRET: process.env.GOOGLE_SECRET || 'unused-id-token-flow' };
console.log('\n→ starting local Supabase (first run downloads images, be patient)…');
const start = spawnSync('npx', ['supabase', 'start'], { stdio: 'inherit', shell: true, env: sbEnv });
if (start.status !== 0) fail('supabase start failed (see output above)');

// 3. keys
const status = execSync('npx supabase status -o env', { encoding: 'utf8', shell: true, env: sbEnv });
const pick = (k) => (status.match(new RegExp(`^${k}="?([^"\\r\\n]+)"?`, 'm')) || [])[1];
const ANON = pick('ANON_KEY');
const SRK = pick('SERVICE_ROLE_KEY');
const API_URL = pick('API_URL') || 'http://127.0.0.1:54321';
if (!ANON || !SRK) fail('could not read ANON_KEY / SERVICE_ROLE_KEY from `supabase status`');
ok('Supabase is up');

// 4. .env.local
const env = `# generated by scripts/bootstrap.mjs on ${new Date().toISOString()}
VITE_SUPABASE_URL='${API_URL}'
VITE_SUPABASE_ANON_KEY="${ANON}"
SUPABASE_SERVICE_ROLE_KEY="${SRK}"

# LLM: Azure OpenAI deployment (model ids azure/<deployment> in the picker)
AZURE_RESOURCE_NAME="${AZURE_RESOURCE}"
AZURE_OPENAI_API_KEY="${AZURE_KEY}"

# local mode: billing bypassed (3M tokens per user), no Stripe needed
ENVIRONMENT="local"
SYNQIT_APP_URL="http://localhost:3000"
WEBHOOK_BASE_URL="http://localhost:3000"
VITE_SENTRY_ENVIRONMENT="local"

# Synqit integration (only needed for "Continue with Synqit" / Google)
VITE_GOOGLE_CLIENT_ID="${GOOGLE_CLIENT_ID}"
VITE_SYNQIT_API_BASE="http://localhost:8000/api"
SYNQIT_API_BASE="http://localhost:8000/api"
${flag('--no-guest') ? '' : `
# No-auth mode: every visitor is signed in as this account. Remove both lines to get the login screen back.
VITE_GUEST_EMAIL="${GUEST_EMAIL}"
VITE_GUEST_PASSWORD="${GUEST_PASSWORD}"
`}`;
writeFileSync(OUT, env, 'utf8');
ok(`wrote ${OUT}`);

// 5. guest account
if (!flag('--no-guest')) {
  const res = await fetch(`${API_URL}/auth/v1/admin/users`, {
    method: 'POST',
    headers: { apikey: SRK, Authorization: `Bearer ${SRK}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: GUEST_EMAIL, password: GUEST_PASSWORD, email_confirm: true, user_metadata: { full_name: 'Synqit Guest' } }),
  });
  const body = await res.json().catch(() => ({}));
  if (res.ok) ok(`guest account ${GUEST_EMAIL} created`);
  else if (/already|exists|registered/i.test(JSON.stringify(body))) {
    // existing account: reset its password to the one we just wrote
    const list = await fetch(`${API_URL}/auth/v1/admin/users?per_page=1000`, { headers: { apikey: SRK, Authorization: `Bearer ${SRK}` } }).then((r) => r.json());
    const u = (list.users || []).find((x) => x.email === GUEST_EMAIL);
    if (u) {
      await fetch(`${API_URL}/auth/v1/admin/users/${u.id}`, { method: 'PUT', headers: { apikey: SRK, Authorization: `Bearer ${SRK}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ password: GUEST_PASSWORD, email_confirm: true }) });
      ok(`guest account ${GUEST_EMAIL} already existed; password synced`);
    }
  } else fail(`guest account creation failed: ${JSON.stringify(body)}`);
}

console.log(`
All set. Next:
  npm run dev          → http://localhost:3000/cad
(Supabase Studio, if you want to look at the data: http://127.0.0.1:54323)
`);
