"""User-facing footprint generator — market-research item #4 (the single
most-requested feature in the corpus: "I just hate making footprints").

Generates IPC-7351-nominal land patterns as valid KiCad `.kicad_mod` text from
a small parametric spec. The pad math is promoted from
`scripts/gen_footprints.py` (whose KiCad selftest validated it to ~0.01 mm);
chip/gull-wing defaults are calibrated against the *verified* footprint cache
(see `scripts/regression_footprint_gen.py`, which asserts generated pads match
KiCad's own within tolerance, offline).

Honesty contract: output is IPC-NOMINAL, not the manufacturer's exact land
pattern. Every generated footprint says so in its description, and the UI
tells the user to verify against the datasheet's recommended pattern.

Families (v1): chip (0402…2512), dual gull-wing (SOIC/SSOP/TSSOP),
quad gull-wing (QFP), leadless (QFN/DFN), BGA grid, DIP (THT),
pin headers 1×N / 2×N (THT).
"""

from __future__ import annotations

from typing import Any

# --------------------------------------------------------------------------- #
# .kicad_mod emission (spec is Y-up, origin at body/pattern centre)
# --------------------------------------------------------------------------- #


def _pad_sexpr(num: str, x: float, y: float, w: float, h: float,
               shape: str = "roundrect", ptype: str = "smd", drill: float = 0.0) -> str:
    y = -y  # spec uses Y-up (math); KiCad is Y-down
    if ptype == "tht":
        layers = '(layers "*.Cu" "*.Mask")'
        drill_s = f" (drill {drill})" if drill else ""
        return (f'  (pad "{num}" thru_hole {shape} (at {x:.4f} {y:.4f}) '
                f'(size {w:.4f} {h:.4f}){drill_s} {layers})')
    layers = '(layers "F.Cu" "F.Paste" "F.Mask")'
    rr = " (roundrect_rratio 0.25)" if shape == "roundrect" else ""
    return (f'  (pad "{num}" smd {shape} (at {x:.4f} {y:.4f}) '
            f'(size {w:.4f} {h:.4f}) {layers}{rr})')


def emit(name: str, pads: list[dict], ep: dict | None = None, descr: str = "",
         tht: bool = False) -> str:
    """Render a footprint to .kicad_mod text: pads + courtyard + silk pin-1
    dot + refdes. pads: [{n,x,y,w,h,shape?,type?,drill?}]."""
    xs = [abs(p["x"]) + p["w"] / 2 for p in pads]
    ys = [abs(p["y"]) + p["h"] / 2 for p in pads]
    cw = round(max(xs) + 0.25, 2)
    ch = round(max(ys) + 0.25, 2)

    lines = [f'(footprint "{name}"', '  (version 20240108)', '  (generator "synqit")',
             '  (layer "F.Cu")',
             f'  (descr "{descr or name} — IPC-nominal land pattern generated by Synqit; '
             'verify against the datasheet recommended pattern before fabrication")',
             f'  (attr {"through_hole" if tht else "smd"})',
             f'  (property "Reference" "REF**" (at 0 {-(ch + 0.8):.2f}) (layer "F.SilkS") '
             '(effects (font (size 1 1) (thickness 0.15))))',
             f'  (property "Value" "{name}" (at 0 {ch + 0.8:.2f}) (layer "F.Fab") '
             '(effects (font (size 1 1) (thickness 0.15))))']
    for p in pads:
        lines.append(_pad_sexpr(p["n"], p["x"], p["y"], p["w"], p["h"],
                                p.get("shape", "roundrect"), p.get("type", "smd"),
                                p.get("drill", 0.0)))
    if ep:
        lines.append(_pad_sexpr(str(ep.get("n", len(pads) + 1)), ep["x"], ep["y"],
                                ep["w"], ep["h"], "rect", "smd"))
    # Courtyard rectangle + a silkscreen pin-1 dot just outside the pad field.
    lines.append(f'  (fp_rect (start {-cw:.2f} {-ch:.2f}) (end {cw:.2f} {ch:.2f}) '
                 '(stroke (width 0.05) (type default)) (layer "F.CrtYd"))')
    p1 = pads[0]
    dot_x = p1["x"] - (p1["w"] / 2 + 0.3) * (1 if p1["x"] < 0 else -1 if p1["x"] > 0 else 0)
    dot_y = -(p1["y"] + (p1["h"] / 2 + 0.3) * (1 if p1["y"] > 0 else -1 if p1["y"] < 0 else 0))
    lines.append(f'  (fp_circle (center {dot_x:.2f} {dot_y:.2f}) (end {dot_x + 0.1:.2f} {dot_y:.2f}) '
                 '(stroke (width 0.2) (type default)) (fill solid) (layer "F.SilkS"))')
    lines.append(")")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# Land-pattern builders (validated math — keep in sync with the KiCad selftest
# in scripts/gen_footprints.py)
# --------------------------------------------------------------------------- #


def perimeter(pins: int, pitch: float, pad_w: float, pad_l: float, span: float,
              *, sides: str, span_y: float | None = None) -> list[dict]:
    """Perimeter pattern shared by leadless (QFN/DFN) and gull-wing (SOIC/QFP).
    sides: 'LR' (dual) or '4' (quad). span = centre-to-centre distance between
    opposite pad rows (span_y for the vertical axis of a rectangular quad).
    Pin 1 top-left, CCW — the JEDEC convention KiCad's own packages follow."""
    pads: list[dict] = []
    if sides == "LR":
        n = pins // 2
        coords = [(i - (n - 1) / 2) * pitch for i in range(n)]
        left = [(-span / 2, coords[::-1][i]) for i in range(n)]    # top→bottom
        right = [(+span / 2, coords[i]) for i in range(n)]         # bottom→top
        for idx, (x, y) in enumerate(left + right, 1):
            pads.append({"n": str(idx), "x": round(x, 4), "y": round(y, 4),
                         "w": pad_l, "h": pad_w})
    elif sides == "4":
        per = pins // 4
        sy = span_y if span_y is not None else span
        coords = [(i - (per - 1) / 2) * pitch for i in range(per)]
        seq: list[tuple[float, float, str]] = []
        seq += [(-span / 2, coords[::-1][i], "h") for i in range(per)]  # left ↓
        seq += [(coords[i], -sy / 2, "v") for i in range(per)]          # bottom →
        seq += [(+span / 2, coords[i], "h") for i in range(per)]        # right ↑
        seq += [(coords[::-1][i], +sy / 2, "v") for i in range(per)]    # top ←
        for idx, (x, y, o) in enumerate(seq, 1):
            w, h = (pad_l, pad_w) if o == "h" else (pad_w, pad_l)
            pads.append({"n": str(idx), "x": round(x, 4), "y": round(y, 4), "w": w, "h": h})
    else:
        raise ValueError(f"bad sides {sides}")
    return pads


def grid(rows: int, cols: int, pitch: float, ball: float) -> list[dict]:
    """BGA/WLP grid, row letters skipping I/O/Q/S/X/Z per JEDEC."""
    row_letters = "ABCDEFGHJKLMNPRTUVWY"
    pads = []
    for r in range(rows):
        for c in range(cols):
            x = (c - (cols - 1) / 2) * pitch
            y = ((rows - 1) / 2 - r) * pitch
            pads.append({"n": f"{row_letters[r]}{c + 1}", "x": round(x, 4), "y": round(y, 4),
                         "w": ball, "h": ball, "shape": "circle"})
    return pads


def dual_tht(pins: int, pitch: float, row_span: float, drill: float, pad: float) -> list[dict]:
    """DIP: left column top→bottom = 1..n, right column bottom→top (JEDEC)."""
    n = pins // 2
    coords = [(i - (n - 1) / 2) * pitch for i in range(n)]
    seq = [(-row_span / 2, coords[::-1][i]) for i in range(n)]
    seq += [(+row_span / 2, coords[i]) for i in range(n)]
    return [{"n": str(i), "x": round(x, 4), "y": round(y, 4), "w": pad, "h": pad,
             "shape": "circle" if i > 1 else "rect", "type": "tht", "drill": drill}
            for i, (x, y) in enumerate(seq, 1)]


def header_tht(rows: int, cols: int, pitch: float, drill: float, pad: float) -> list[dict]:
    """Pin header, KiCad convention: pin 1 top-left; 2×N numbers zigzag
    (1,2 across the first row, 3,4 across the second…)."""
    pads = []
    num = 1
    for r in range(cols):          # cols = positions along the strip
        y = -(r - (cols - 1) / 2) * pitch
        for c in range(rows):      # rows = pins across (1 or 2)
            x = (c - (rows - 1) / 2) * pitch
            pads.append({"n": str(num), "x": round(x, 4), "y": round(y, 4),
                         "w": pad, "h": pad,
                         "shape": "circle" if num > 1 else "rect",
                         "type": "tht", "drill": drill})
            num += 1
    return pads


