# IPC-7351 nominal fillet goals (toe / heel / side), density level N.
_CHIP_JT, _CHIP_JH, _CHIP_JS = 0.4, 0.1, 0.075
_GW_JT, _GW_JH = 0.45, 0.45


def generate(family: str, params: dict[str, Any]) -> dict[str, Any]:
    """Generate a footprint. Returns {name, content, pads, tht, warnings}.
    Raises ValueError on a bad spec — the API maps it to a 422."""
    spec = FAMILIES.get(family)
    if spec is None:
        raise ValueError(f"Unknown family '{family}'. One of: {', '.join(FAMILIES)}")
    # Fill defaults + validate numerics.
    p: dict[str, Any] = {}
    for f in spec["params"]:
        raw = params.get(f["key"], f["default"])
        if f["type"] == "int":
            raw = int(raw)
            if not (f.get("min", raw) <= raw <= f.get("max", raw)):
                raise ValueError(f"{f['label']}: must be {f['min']}–{f['max']}")
        elif f["type"] == "float":
            raw = float(raw)
            if raw < 0 or raw > 100:
                raise ValueError(f"{f['label']}: out of range")
        elif f["type"] == "enum" and str(raw) not in f["options"]:
            raise ValueError(f"{f['label']}: must be one of {f['options']}")
        p[f["key"]] = raw

    warnings: list[str] = []
    ep = None
    tht = False

    if family == "chip":
        length, width, t = CHIP_SIZES[str(p["size"])]
        z = length + 2 * _CHIP_JT
        g = length - 2 * t - 2 * _CHIP_JH
        pad_l = (z - g) / 2
        cx = (z + g) / 4
        pad_w = width + 2 * _CHIP_JS
        pads = [
            {"n": "1", "x": round(-cx, 4), "y": 0.0, "w": round(pad_l, 3), "h": round(pad_w, 3)},
            {"n": "2", "x": round(cx, 4), "y": 0.0, "w": round(pad_l, 3), "h": round(pad_w, 3)},
        ]
        name = f"Synqit_{p['size']}"
    elif family in ("dual", "quad"):
        pins, pitch, span, lead = p["pins"], p["pitch"], p["span"], p["lead_len"]
        divisor = 2 if family == "dual" else 4
        if pins % divisor:
            raise ValueError(f"Pin count must be a multiple of {divisor}")
        if family == "quad" and (pins // 4 - 1) * pitch >= span - 1:
            raise ValueError("Pins per side don't fit inside the lead span at this pitch")
        z = span + 2 * _GW_JT
        g = span - 2 * lead - 2 * _GW_JH
        if g <= 0:
            raise ValueError("Lead span too small for the lead length")
        pad_l = round((z - g) / 2, 3)
        centre_span = round((z + g) / 2, 4)  # centre-to-centre between rows
        pad_w = round(min(0.6 * pitch, pitch - 0.2) if pitch >= 0.5 else 0.55 * pitch, 3)
        if pad_w < 0.2:
            warnings.append(f"Pad width {pad_w} mm is very fine — confirm your fab can do it.")
        pads = perimeter(pins, pitch, pad_w, pad_l, centre_span,
                         sides="LR" if family == "dual" else "4")
        kind = "SOIC/SSOP" if family == "dual" else "QFP"
        name = f"Synqit_{kind.split('/')[0]}-{pins}_P{pitch}mm"
    elif family == "leadless":
        pins, pitch, span = p["pins"], p["pitch"], p["span"]
        sides = str(p["sides"])
        if pins % (4 if sides == "4" else 2):
            raise ValueError("Pin count must divide evenly across the sides")
        pads = perimeter(pins, pitch, p["pad_w"], p["pad_l"], span, sides=sides)
        if p["ep"]:
            ep = {"x": 0, "y": 0, "w": p["ep"], "h": p["ep"], "n": str(pins + 1)}
        name = f"Synqit_{'QFN' if sides == '4' else 'DFN'}-{pins}_P{pitch}mm"
    elif family == "bga":
        pads = grid(p["rows"], p["cols"], p["pitch"], p["ball"])
        warnings.append("BGA fanout/escape routing is not checked — confirm via-in-pad rules with your fab.")
        name = f"Synqit_BGA-{p['rows'] * p['cols']}_P{p['pitch']}mm"
        tht = False
    elif family == "dip":
        pins = p["pins"]
        if pins % 2:
            raise ValueError("Pin count must be even")
        pads = dual_tht(pins, 2.54, p["row_span"], drill=0.8, pad=1.6)
        name = f"Synqit_DIP-{pins}_W{p['row_span']}mm"
        tht = True
    elif family == "castellated":
        # A castellated module's pads are HALF-PLATED SLOTS on the board edge:
        # the module's own edge is milled through the plated hole, so the
        # carrier board sees a rectangular SMD pad that reaches the outline and
        # must extend inboard far enough for a visible solder fillet. Requested
        # by the 2026-08-20 review round (a "custom ESP32-S3 dev board with
        # castellated GPIO pads" had to fall back to two 1x10 pin headers,
        # which is a different product).
        per_side, pitch = p["per_side"], p["pitch"]
        bw, bh = p["board_w"], p["board_h"]
        pad_w, pad_l = p["pad_w"], p["pad_l"]
        sides = str(p["sides"])
        run = (per_side - 1) * pitch
        if sides == "LR" and run > bh - pitch:
            raise ValueError(
                f"{per_side} pads at {pitch} mm need {run:.1f} mm but the module is only "
                f"{bh} mm long — increase the length or reduce the pitch"
            )
        if sides == "4" and run > min(bw, bh) - pitch:
            raise ValueError("Pads do not fit along the shorter side at this pitch")
        if pad_w >= pitch:
            raise ValueError(f"Pad width {pad_w} mm leaves no gap at {pitch} mm pitch")
        if pad_l < 1.0:
            warnings.append(
                "A castellation shorter than 1 mm inboard gives the solder no fillet to "
                "climb — 1.5-2 mm is normal."
            )
        pads = []
        n = 1
        def _row(cx: float, cy: float, horizontal: bool, count: int, reverse: bool) -> None:
            nonlocal n, pads
            span = (count - 1) * pitch
            for i in range(count):
                k = count - 1 - i if reverse else i
                off = -span / 2 + k * pitch
                if horizontal:
                    x, y = cx + off, cy
                    w, h = pad_w, pad_l
                else:
                    x, y = cx, cy + off
                    w, h = pad_l, pad_w
                pads.append({"n": str(n), "x": round(x, 4), "y": round(y, 4),
                             "w": round(w, 3), "h": round(h, 3)})
                n += 1
        # Pin 1 top-left, numbering counter-clockwise (the module convention).
        _row(-bw / 2 + pad_l / 2, 0.0, False, per_side, reverse=False)   # left edge
        if sides == "4":
            _row(0.0, -bh / 2 + pad_l / 2, True, per_side, reverse=False)  # bottom
        _row(bw / 2 - pad_l / 2, 0.0, False, per_side, reverse=True)     # right edge
        if sides == "4":
            _row(0.0, bh / 2 - pad_l / 2, True, per_side, reverse=True)    # top
        warnings.append(
            "Castellated pads are half-plated slots on the module edge: the FAB must "
            "plate the edge (specify 'castellated holes' / edge plating on the order) "
            "and the carrier board's pads should extend "
            f"{pad_l} mm inboard for the fillet."
        )
        name = f"Synqit_Castellated_{'4x' if sides == '4' else '2x'}{per_side}_P{pitch}mm"
    elif family == "header":
        pads = header_tht(p["rows"], p["count"], 2.54, drill=1.0, pad=1.7)
        name = f"Synqit_Header_{p['rows']}x{p['count']:02d}_P2.54mm"
        tht = True
    else:  # pragma: no cover — FAMILIES lookup already guards
        raise ValueError(family)

    content = emit(name, pads, ep=ep, tht=tht)
    return {
        "name": name,
        "content": content,
        "pads": pads + ([{**ep, "shape": "rect"}] if ep else []),
        "tht": tht,
        "warnings": warnings,
    }
