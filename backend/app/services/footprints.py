def _qfn(name: str, width: float, height: float, pin_count: int, pitch: float) -> Footprint:
    """Generic QFN with pin_count pins evenly distributed around 4 sides."""
    per_side = pin_count // 4
    pads = []
    half_w = width / 2
    half_h = height / 2
    pad_size = pitch * 0.6
    for i in range(per_side):
        offset = -((per_side - 1) * pitch) / 2 + i * pitch
        pads.append(FootprintPad(pin_number=str(i + 1), x=-half_w, y=offset, width=pad_size * 1.2, height=pad_size, pad_type="smd"))
        pads.append(FootprintPad(pin_number=str(i + 1 + per_side), x=offset, y=+half_h, width=pad_size, height=pad_size * 1.2, pad_type="smd"))
        pads.append(FootprintPad(pin_number=str(i + 1 + 2 * per_side), x=+half_w, y=offset, width=pad_size * 1.2, height=pad_size, pad_type="smd"))
        pads.append(FootprintPad(pin_number=str(i + 1 + 3 * per_side), x=offset, y=-half_h, width=pad_size, height=pad_size * 1.2, pad_type="smd"))
    return Footprint(name=name, width=width + 1.0, height=height + 1.0, pads=pads)


def _usb_c_recep(name: str) -> Footprint:
    """USB-C 24-pin SMD receptacle: ~9x7.3mm, A1-A12 (top row) + B1-B12 (bottom
    row, USB-C is reversible) + 4 shield mounts. Real receptacle pad layout."""
    pads = []
    # Top row A1..A12 — A1 leftmost, A12 rightmost.
    for i in range(12):
        pads.append(
            FootprintPad(
                pin_number=f"A{i + 1}",
                x=-2.75 + i * 0.5,
                y=-2.5,
                width=0.3,
                height=1.2,
                pad_type="smd",
            )
        )
    # Bottom row B1..B12 — USB-C is reversible so B is the mirror of A.
    # B1 is opposite A12, B12 opposite A1.
    for i in range(12):
        pads.append(
            FootprintPad(
                pin_number=f"B{i + 1}",
                x=+2.75 - i * 0.5,
                y=+2.5,
                width=0.3,
                height=1.2,
                pad_type="smd",
            )
        )
    # Shield/mount tabs on the sides.
    pads.append(FootprintPad(pin_number="S1", x=-4.32, y=0, width=1.2, height=2.2, pad_type="smd"))
    pads.append(FootprintPad(pin_number="S2", x=+4.32, y=0, width=1.2, height=2.2, pad_type="smd"))
    return Footprint(name=name, width=9.0, height=7.3, pads=pads)


