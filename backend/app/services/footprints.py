def _pin_header(name: str, count: int, pitch: float = 2.54, rows: int = 1) -> Footprint:
    """Through-hole pin header, single or double row."""
    pads: list[FootprintPad] = []
    width = (count - 1) * pitch + 2.0 if rows == 1 else (count // 2 - 1) * pitch + 2.0
    height = 2.5 if rows == 1 else (rows - 1) * pitch + 2.5
    if rows == 1:
        for i in range(count):
            pads.append(
                FootprintPad(
                    pin_number=str(i + 1),
                    x=-((count - 1) * pitch) / 2 + i * pitch,
                    y=0,
                    width=0.7,
                    shape="circle",
                    pad_type="tht",
                )
            )
    else:
        per_row = count // rows
        for row in range(rows):
            for col in range(per_row):
                pads.append(
                    FootprintPad(
                        pin_number=str(row * per_row + col + 1),
                        x=-((per_row - 1) * pitch) / 2 + col * pitch,
                        y=-((rows - 1) * pitch) / 2 + row * pitch,
                        width=0.5,
                        shape="circle",
                        pad_type="tht",
                    )
                )
    return Footprint(name=name, width=width, height=height, pads=pads)


