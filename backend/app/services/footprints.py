"""Footprint shape data for the parts in the curated library.

Each entry returns a `Footprint` with bounding box dimensions and pad positions
in millimeters, in the footprint's local coordinate system (origin at center).

Two layers (task 3.2):
1. **Verified** — when KiCad is installed, `_resolve_from_kicad` loads the part's
   real `Lib:Name` footprint from KiCad's stock libraries (exact pads/courtyard)
   and stamps `confidence="verified"`. This is the manufacturing-ready path.
2. **Approximate** — the hand-maintained parametric geometry below is the fallback
   when KiCad is absent or the part's footprint string doesn't resolve to a real
   KiCad footprint. Good enough for placement, routing, and visualisation, but
   honestly flagged as not fab-final (and surfaced by verifier rule PCB_R07).
"""

from __future__ import annotations

import json
from pathlib import Path

from app.models import Footprint, FootprintPad, LibraryPart
from app.services import kicad_bridge, library

# Disk-backed cache of real-KiCad footprint geometry, keyed by the `Lib:Name`
# string. `for_part` is on hot paths (placement, routing, summary, verifier), so
# without this a fresh process would shell out to KiCad (~0.7s) per unique
# footprint on the first build. Only *positive* results are persisted: a
# negative (KiCad couldn't resolve it) is kept in-memory only, so a footprint
# that failed to resolve because KiCad was absent isn't permanently poisoned —
# it re-resolves once KiCad is installed. Footprint geometry is immutable, so a
# cached positive is valid for the life of the file. Pre-generated by
# `scripts.build_footprint_cache`; self-populates at runtime otherwise.
_CACHE_PATH = Path(__file__).resolve().parent.parent / "library" / "footprint_cache.json"

_kicad_fp_cache: dict[str, Footprint | None] = {}
_cache_loaded = False


def _load_cache() -> None:
    global _cache_loaded
    if _cache_loaded:
        return
    _cache_loaded = True
    try:
        raw = json.loads(_CACHE_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    for fpid, val in raw.items():
        if fpid.startswith("_"):
            continue  # reserved for metadata
        try:
            _kicad_fp_cache[fpid] = Footprint(**val) if val else None
        except Exception:
            pass


def _persist_cache() -> None:
    """Write positive (resolved) entries to disk atomically. Negatives are not
    persisted (see the cache note above)."""
    try:
        raw = {
            fpid: fp.model_dump()
            for fpid, fp in _kicad_fp_cache.items()
            if fp is not None
        }
        tmp = _CACHE_PATH.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(raw), encoding="utf-8")
        tmp.replace(_CACHE_PATH)
    except OSError:
        pass


def _resolve_from_kicad(part: LibraryPart, persist: bool = True) -> Footprint | None:
    """Load the part's real footprint geometry from KiCad's stock libraries via
    the headless bridge (task 3.1). Returns a `Footprint` with exact pads and
    courtyard, or None when KiCad is absent / the footprint id is not a real
    `Lib:Name` / it isn't in any installed library. Cached (disk + memory)."""
    _load_cache()
    fpid = (part.footprint or "").strip()
    if ":" not in fpid:
        return None  # not a KiCad Lib:Name (e.g. bare "SMD"/"MODULE") — skip
    if fpid in _kicad_fp_cache:
        cached = _kicad_fp_cache[fpid]
        return cached.model_copy(deep=True) if cached is not None else None

    result = kicad_bridge.run_script("dump_footprint.py", {"footprint": fpid})
    if not result.success:
        _kicad_fp_cache[fpid] = None  # in-memory only; not persisted
        return None

    d = result.data
    try:
        fp = Footprint(
            name=d["name"],
            width=d["width"],
            height=d["height"],
            courtyard_w=d.get("courtyard_w", 0.0),
            courtyard_h=d.get("courtyard_h", 0.0),
            pads=[FootprintPad(**p) for p in d.get("pads", [])],
        )
    except Exception:
        _kicad_fp_cache[fpid] = None
        return None

    _kicad_fp_cache[fpid] = fp
    if persist:
        _persist_cache()
    return fp.model_copy(deep=True)


